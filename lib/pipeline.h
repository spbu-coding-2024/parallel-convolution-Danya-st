#ifndef PIPELINE_H
#define PIPELINE_H

/*
 * Конвейер потоковой обработки директории изображений:
 *
 *   читатель (1 поток) -> очередь read_q -> воркеры (N потоков, свёртка)
 *                      -> очередь proc_q -> писатель (1 поток)
 *
 * Обе очереди ограничены по длине: если читатель быстрее свёртки, он
 * блокируется на push и не может забить память декодированными картинками.
 *
 * ИСПРАВЛЕНО (задача 3, "Дубликаты кода"): очередь и конвейер раньше были
 * скопированы в stream_main.c и bench_stream.c (с разными константами
 * QUEUE_CAPACITY/QUEUE_SIZE, MAX_PATH 1024/512). Теперь одна реализация,
 * которую используют stream_main, bench_stream и тесты.
 */

#include "conv.h"
#include "filters.h"

typedef struct {
  /* число рабочих потоков свёртки, >= 1 (ограничений сверху нет) */
  int num_workers;
  /* ёмкость каждой из двух очередей, >= 1 */
  int queue_capacity;
  /* стратегия свёртки внутри воркера */
  ParallelMode mode;
  /* размер плитки для MODE_TILE */
  int tile_w, tile_h;
  /* число потоков OpenMP внутри каждого воркера; 0 - не менять */
  int omp_threads;
} PipelineConfig;

/*
 * Статистика прогона. Времена стадий - СУММАРНОЕ процессорное время
 * потоков стадии (см. cpu_now() в pipeline.c), ожидания - суммарное время
 * простоя на очереди. По ним видно узкое место конвейера (закон Амдала:
 * ускорение ограничено самой медленной стадией).
 */
typedef struct {
  /* изображений прочитано и поставлено в обработку */
  int read_ok;
  /* файлов, которые не удалось декодировать */
  int read_failed;
  /* изображений успешно записано */
  int written;
  /* изображений, которые не удалось записать (включая нехватку памяти) */
  int write_failed;
  /* настенное время всего прогона */
  double wall_sec;
  /* декодирование (stbi_load) */
  double read_busy_sec;
  /* свёртка */
  double conv_busy_sec;
  /* кодирование и запись (stbi_write_png) */
  double write_busy_sec;
  /* читатель ждёт свободного места в read_q (стадия свёртки не успевает) */
  double reader_blocked_sec;
  /* воркеры ждут данных из read_q (читатель не успевает) */
  double workers_starved_sec;
  /* воркеры ждут места в proc_q (писатель не успевает) */
  double workers_blocked_sec;
  /* писатель ждёт данных из proc_q (воркеры не успевают) */
  double writer_starved_sec;
  /* максимальная заполненность очередей за прогон */
  int read_q_peak;
  int proc_q_peak;
} PipelineStats;

/*
 * Обрабатывает все изображения (.png, .jpg, .jpeg, .bmp без учёта регистра)
 * из in_dir и пишет результат в out_dir (создаётся, если его нет).
 * Имя результата: для .png - то же имя, для остальных - имя + ".png"
 * (например photo.jpg -> photo.jpg.png), потому что в файле всегда PNG и
 * имя не должно ему противоречить.
 *
 * Возвращает 0, если конвейер отработал (возможные ошибки отдельных файлов
 * смотрите в stats: read_failed / write_failed), и -1, если запустить его
 * не удалось (не открывается in_dir, нельзя создать out_dir, неверные
 * параметры, не создан ни один рабочий поток). Никогда не зависает.
 * stats может быть NULL.
 */
int pipeline_run(const char *in_dir, const char *out_dir, const Filter *filter,
                 const PipelineConfig *cfg, PipelineStats *stats);

#endif